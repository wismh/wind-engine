#include "shader_cook/slang_compiler.h"

#include <cstdint>
#include <fstream>
#include <iostream>
#include <iterator>
#include <string>
#include <vector>

namespace {

std::string read_file(const std::string& path) {
    std::ifstream in(path, std::ios::binary);
    if (!in) {
        return {};
    }
    return std::string(std::istreambuf_iterator<char>(in), std::istreambuf_iterator<char>());
}

bool write_array(std::ostream& out, const std::string& name, const std::vector<std::uint32_t>& words) {
    out << "inline constexpr std::uint32_t " << name << "[] = {\n";
    for (std::size_t i = 0; i < words.size(); ++i) {
        if (i % 8 == 0) {
            out << "    ";
        }
        out << "0x" << std::hex << words[i] << "u,";
        out << std::dec;
        if (i % 8 == 7 || i + 1 == words.size()) {
            out << "\n";
        } else {
            out << " ";
        }
    }
    out << "};\n";
    return static_cast<bool>(out);
}

bool emit_inc(const std::string& slang_path, const std::string& inc_path, const std::string& prefix) {
    const std::string source = read_file(slang_path);
    if (source.empty()) {
        std::cerr << "failed to read " << slang_path << "\n";
        return false;
    }
    const auto compiled = engine::render::compile_slang_shader(source);
    if (!compiled) {
        std::cerr << slang_path << ": " << compiled.error() << "\n";
        return false;
    }
    std::ofstream out(inc_path, std::ios::trunc);
    if (!out) {
        std::cerr << "failed to write " << inc_path << "\n";
        return false;
    }
    out << "// Generated by shader_builtin_spirv from tools/shader_cook/shaders/. Do not edit.\n";
    out << "#pragma once\n\n#include <cstdint>\n\nnamespace engine::render {\n\n";
    if (!write_array(out, "k" + prefix + "VertexSpirv", compiled->vertex_spirv)
            || !write_array(out, "k" + prefix + "FragmentSpirv", compiled->fragment_spirv)) {
        return false;
    }
    out << "\n}\n";
    return static_cast<bool>(out);
}

}

int main(int argc, char** argv) {
    if (argc != 5) {
        std::cerr << "usage: shader_builtin_spirv <particle.slang> <ui.slang> <particle.inc> <ui.inc>\n";
        return 2;
    }
    if (!emit_inc(argv[1], argv[3], "Particle") || !emit_inc(argv[2], argv[4], "Ui")) {
        return 1;
    }
    return 0;
}
