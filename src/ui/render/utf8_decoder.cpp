std::uint32_t Utf8Decoder::step(unsigned char byte) noexcept {
    const std::uint32_t type = kUtf8Dfa[byte];
    codepoint = state != kAccept ? (byte & 0x3Fu) | (codepoint << 6) : (0xFFu >> type) & byte;
    state = kUtf8Dfa[256 + state + type];
    return state;
}

